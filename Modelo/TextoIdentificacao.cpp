std::string TiraParentesesDoFim(const std::string &s)
{
    // \s*\( ... [^\)]+ \) \s*$ : o casamento termina no fim do texto (o "$" do .NET aceita tambem
    // um \n final). O Regex tenta as posicoes da esquerda para a direita e fica com a primeira que
    // casa: o espaco antes de um "(" cujo conteudo (sem ")") vai ate um ")" seguido so de espaco.
    std::vector<uint32_t> c = Base::CodePoints(s);
    size_t fim = c.size();
    if (fim > 0 && c[fim - 1] == '\n') fim--;          // o "$" antes do \n final
    size_t k = fim;
    while (k > 0 && EhEspaco(c[k - 1])) k--;           // \s* do fim
    if (k == 0 || c[k - 1] != ')') return s;
    size_t fecha = k - 1;                               // o ")" final
    // o conteudo [^\)]+ nao tem ")": os "(" candidatos ficam depois do ")" anterior
    size_t ini = 0;
    for (size_t i = fecha; i > 0; i--)
        if (c[i - 1] == ')') { ini = i; break; }
    static const char *excecoes[] = {"ao vivo", "live", "acustico", "acoustic", "remastered", "deluxe"};
    for (size_t p = ini; p < fecha; p++)
    {
        if (c[p] != '(') continue;
        if (p + 1 >= fecha) continue;                   // [^\)]+ precisa de ao menos um caractere
        bool excecao = false;
        for (const char *e : excecoes)
        {
            size_t n = Base::CodePoints(e).size();
            // (?!(?:...)\b): a palavra e, logo depois, uma fronteira (\b: nao-palavra ou fim)
            if (CasaEm(c, p + 1, e) && (p + 1 + n >= c.size() || !EhPalavra(c[p + 1 + n])))
            {
                excecao = true;
                break;
            }
        }
        if (excecao) continue;
        size_t de = p;
        while (de > 0 && EhEspaco(c[de - 1])) de--;     // \s* antes do "("
        // o Regex comeca na primeira posicao que casa: o espaco antes do "(" vai junto
        return Trecho(c, 0, de) + Trecho(c, fim, c.size());
    }
    return s;
}

std::string TiraAnotacoes(const std::string &s, const std::string &substituto,
                          const std::vector<std::string> &palavras)
{
    // \s*[\(\[] [^\]\)]* (palavra)? [^\]\)]* [\)\]], substituindo todas as ocorrencias, da esquerda
    // para a direita, sem sobreposicao (Regex.Replace).
    std::vector<uint32_t> c = Base::CodePoints(s);
    std::string r;
    size_t i = 0;
    while (i < c.size())
    {
        size_t j = i;
        while (j < c.size() && EhEspaco(c[j])) j++;
        if (j < c.size() && (c[j] == '(' || c[j] == '['))
        {
            size_t q = j + 1;
            while (q < c.size() && c[q] != ')' && c[q] != ']') q++;
            if (q < c.size())
            {
                bool casa = palavras.empty();
                for (size_t p = j + 1; !casa && p < q; p++)
                    for (const std::string &w : palavras)
                        if (p + Base::CodePoints(w).size() <= q && CasaEm(c, p, w)) { casa = true; break; }
                if (casa)
                {
                    r += substituto;
                    i = q + 1;
                    continue;
                }
            }
        }
        Base::AcrescentaUtf8(r, c[i]);
        i++;
    }
    return r;
}

std::string TiraSufixoNumerico(const std::string &s)
{
    std::vector<uint32_t> c = Base::CodePoints(s);
    size_t fim = c.size();
    if (fim > 0 && c[fim - 1] == '\n') fim--;
    if (fim == 0 || c[fim - 1] != ')') return s;
    size_t k = fim - 1;
    size_t d = k;
    while (d > 0 && EhDigito(c[d - 1])) d--;
    if (d == k || d == 0 || c[d - 1] != '(') return s;
    size_t a = d - 1;
    size_t e = a;
    while (e > 0 && EhEspaco(c[e - 1])) e--;
    if (e == a) return s;                               // \s+: ao menos um espaco
    return Trecho(c, 0, e) + Trecho(c, fim, c.size());
}

