Json Desserializa(const std::string &strJson)
{
    // ARCA-ORIGINAL: o JavaScriptSerializer recusa texto acima de MaxJsonLength (2.097.152
    // caracteres, o padrao, que o original nao muda). Um lancamento enorme do Discogs (caixa com
    // centenas de faixas) cairia aqui. Portado igual.
    if (Base::Caracteres(strJson) > 2097152)
        throw Base::InvalidOperationException(
            "Erro durante a serialização ou desserialização usando JSON JavaScriptSerializer. O comprimento "
            "da cadeia de caracteres excede o valor definido na propriedade maxJsonLength.");
    Json j = Base::JsonDe(strJson);
    if (!Base::JsonValido(j)) throw Base::ArgumentException("Primitivo JSON inválido.");
    if (j.is_null()) return j;                                       // "null" -> null
    if (!j.is_object())
        throw Base::InvalidOperationException("Não é possível converter o objeto para o tipo Dictionary.");
    return j;
}

std::string TextoDe(const Json &v)
{
    if (v.is_null()) throw std::runtime_error("Referência de objeto não definida para uma instância de um objeto.");
    if (v.is_string()) return v.get<std::string>();
    if (v.is_boolean()) return v.get<bool>() ? "True" : "False";
    if (v.is_number_integer()) return std::to_string(v.get<long long>());
    if (v.is_number_unsigned()) return std::to_string(v.get<unsigned long long>());
    if (v.is_number_float())
    {
        // decimal.ToString() na cultura pt-BR: virgula decimal
        std::string t = v.dump();
        std::replace(t.begin(), t.end(), '.', ',');
        return t;
    }
    if (v.is_array()) return "System.Collections.ArrayList";
    return "System.Collections.Generic.Dictionary`2[System.String,System.Object]";
}

int64_t ParaInt64(const Json &v)
{
    if (v.is_null()) return 0;
    if (v.is_number_integer()) return v.get<long long>();
    if (v.is_number_unsigned()) return (int64_t) v.get<unsigned long long>();
    if (v.is_number_float()) return (int64_t) std::nearbyint(v.get<double>());   // Convert: arredonda ao par
    if (v.is_boolean()) return v.get<bool>() ? 1 : 0;
    if (v.is_string())
    {
        int64_t x;
        if (Base::TentaInt64(v.get<std::string>(), x)) return x;
        throw std::runtime_error("A cadeia de caracteres de entrada não estava em um formato correto.");
    }
    throw std::runtime_error("Não é possível converter um objeto do tipo para o tipo 'System.IConvertible'.");
}

int ParaInt32(const Json &v)
{
    int64_t x = ParaInt64(v);
    if (x < INT32_MIN || x > INT32_MAX)
        throw std::runtime_error("O valor era muito grande ou muito pequeno para um Int32.");
    return (int) x;
}

